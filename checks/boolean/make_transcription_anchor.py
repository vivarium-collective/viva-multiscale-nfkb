"""Write checks/boolean/transcription-anchor-{fast,slow}/: NF-kB's target genes keep Lipniacki's clock whatever k_time is.

The reduced network writes Calzone's $TransRate as $r_tx / $k_time inside rates that are all multiplied by $k_time, so
a target gene switches on at r_tx per second, the rate measured from Lipniacki 2004's own NF-kB -> A20 delay
(workspace/datasets/calzone2010_cellfate/processed/transcription_anchor.json, written by anchor_transcription.py).

The check holds NF-kB on with Calzone's own mutant switch ($High_NFkB = 1), with TNF off so no death signal starts.
Each of the four direct targets (BCL2, cFLIP, mXIAP and Survival, each with logic NFkB) is then an absorbing switch
at rate r_tx. Over MaBoSS's last window [a, b] its probability averages 1 - (exp(-r a) - exp(-r b)) / (r (b - a)). The
interval is Lipniacki's delay itself, so each gene is about half on at its end. The same oracle must hold at two death
clocks 100x apart (k_time = 1/60 and 1/6000 Calzone units per second). That shows the sweep moves the death machinery
and not gene expression.

    uv run --project compose python -I checks/boolean/make_transcription_anchor.py
"""

from __future__ import annotations

import json
import math
import re
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "workspace" / "datasets" / "calzone2010_cellfate" / "processed"
HERE = Path(__file__).resolve().parent
TARGETS = ("BCL2", "cFLIP", "mXIAP", "Survival")
WINDOWS, SAMPLES, ABS_TOL = 20, 50_000, 0.01


def write(name: str, k_time: float, network: str, r_tx: float, interval: float) -> None:
    nodes = sorted(re.findall(r"^node\s+(\w+)", network, re.MULTILINE))
    on = {"FADD", "ATP"}
    a, b = interval * (WINDOWS - 1) / WINDOWS, interval
    expected = 1.0 - (math.exp(-r_tx * a) - math.exp(-r_tx * b)) / (r_tx * (b - a))
    initial = {n: float(n in on) for n in nodes}
    document = {
        "global_time_precision": 6,
        "state": {
            "node_state": initial,
            "node_probabilities": dict(initial),
            "parameters": {},
            "steps": 0,
            "cellfate": {
                "_type": "process",
                "address": "local:viva_maboss.processes.MaBoSSProcess",
                "config": {
                    "network": network,
                    "parameters": {"High_NFkB": 1.0, "Low_CASP8": 0.0, "Low_RIP1": 0.0, "u_NFkB": 0.0,
                                   "d_NFkB": 0.0, "u_TNF": 0.0, "d_TNF": 0.0, "k_time": k_time, "r_tx": r_tx},
                    "initial_state": {n: 1.0 for n in on},
                    "sample_count": SAMPLES,
                    "windows_per_interval": WINDOWS,
                    "seed": 13,
                },
                "interval": interval,
                "inputs": {"node_state": ["node_state"], "node_probabilities": ["node_probabilities"],
                           "parameters": ["parameters"], "steps": ["steps"]},
                "outputs": {"node_state": ["node_state"], "node_probabilities": ["node_probabilities"],
                            "steps": ["steps"]},
            },
            "emitter": {
                "_type": "step",
                "address": "local:RAMEmitter",
                "config": {"emit": {"node_probabilities": "map[float]", "steps": "integer"}},
                "inputs": {"node_probabilities": ["node_probabilities"], "steps": ["steps"]},
            },
        },
    }
    case = {
        "description": (
            f"NF-kB's target genes on Lipniacki's clock at k_time = {k_time:.6g} Calzone units/s. NFkB held on "
            f"($High_NFkB = 1), TNF off, one interval of {interval:g} s (Lipniacki's NF-kB -> A20 half-rise delay) in "
            f"{WINDOWS} windows, {SAMPLES} trajectories. {', '.join(TARGETS)} each switch on at r_tx = {r_tx:.6g}/s "
            "(transcription_anchor.json). Analytic window average over the last window: "
            f"{expected:.6f}. The same value is expected at both death clocks. Generated by "
            "checks/boolean/make_transcription_anchor.py."
        ),
        "document": "document.pbg",
        "interval": interval,
        "scale_level": "molecule",
        "expect": [
            {"kind": "rows", "emitter": "emitter", "min": 2},
            {"kind": "scalar", "emitter": "emitter", "field": "steps", "expected": 1},
            *({"kind": "scalar", "emitter": "emitter", "field": f"node_probabilities.{n}", "expected": expected,
               "abs": ABS_TOL} for n in TARGETS),
        ],
    }
    out = HERE / name
    out.mkdir(exist_ok=True)
    (out / "document.pbg").write_text(json.dumps(document, indent=2) + "\n")
    (out / "case.yaml").write_text(yaml.safe_dump(case, sort_keys=False, width=120))
    print(f"wrote checks/boolean/{name}: k_time {k_time:.6g}, expected P(target on) = {expected:.6f}")


def main() -> None:
    network = (DATA / "cellfate_reduced.bnd").read_text()
    anchor = json.loads((DATA / "transcription_anchor.json").read_text())
    r_tx, delay = anchor["r_tx_per_s"], anchor["target_delay_s"]
    write("transcription-anchor-fast", 1.0 / 60.0, network, r_tx, delay)
    write("transcription-anchor-slow", 1.0 / 6000.0, network, r_tx, delay)


if __name__ == "__main__":
    main()
