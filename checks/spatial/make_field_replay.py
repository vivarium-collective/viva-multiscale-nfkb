"""Generate `spatial/field-replay`: the TNF the distance study replays is what the field composite gives each cell.

The distance study (s3-distance, decision 59) does not run the field with its cells. It replays the TNF at each cell's
surface ring recorded by one 24 h run of the field at the process level (analysis/exposure-design/exposure_24h.py,
`exposure_24h_band1.json`, per unit bolus). That is exact only if the field composite, run through compose-api's
runner, gives the same TNF at the same instants. This case runs the far-bolus check's own composite (decision 39's
field, three RegionMean rings, a bolus of mass M; checks/spatial/make_far_bolus.py `document`) and checks that each
ring's TNF every 30 s for the first hour is M times the recorded series.

`--negative scaled` writes `field-replay-negative`, whose oracle is 1% too high; it must fail at every row where the
TNF is resolved.

    uv run --project compose --frozen python -I checks/spatial/make_field_replay.py [--negative scaled]
"""

from __future__ import annotations

import argparse
import importlib.util
import json
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
FAR_BOLUS = HERE / "make_far_bolus.py"
FIELD = ROOT / "analysis" / "exposure-design" / "exposure_24h_band1.json"
END, STEP = 3600.0, 30.0


def _far():
    spec = importlib.util.spec_from_file_location("make_far_bolus", FAR_BOLUS)
    if spec is None or spec.loader is None:
        raise SystemExit(f"cannot load {FAR_BOLUS}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--negative", choices=("scaled",), help="write a copy whose oracle is 1% off; it must fail")
    args = parser.parse_args()
    far = _far()
    field = json.loads(FIELD.read_text())
    if not field["band"] or field["sample_s"] != STEP or field["time_s"][0] != STEP:
        raise SystemExit(f"{FIELD} is not the banded field sampled every {STEP} s from {STEP} s")
    if field["cells_um"] != far.CELLS:
        raise SystemExit(f"{FIELD}'s rings {field['cells_um']} are not the far-bolus check's {far.CELLS}")
    scale = far.M * (1.01 if args.negative else 1.0)
    expect: list[dict] = [{"kind": "rows", "emitter": "emitter", "min": int(END / STEP) + 1}]
    for ring in far.CELLS:
        for row in range(1, int(END / STEP) + 1):
            expected = scale * field["tnf_at_cell"][ring][row - 1]
            # the far ring's TNF is below 1e-12 of its peak until about 10 min: nothing to compare there
            expect.append({"kind": "scalar", "emitter": "emitter", "field": f"tnf_{ring}.TNF", "row": row,
                           "expected": expected, "rel": 1e-9, "abs": 1e-12})
    case_name = "field-replay" + ("-negative" if args.negative else "")
    description = (
        f"NEGATIVE ({args.negative}): must fail. Delete after running." if args.negative else
        "The TNF the distance study replays (decision 59) is what the field composite gives each cell: the far-bolus "
        f"check's composite (decision 39's field, bolus mass {far.M:g} uM um^2, three RegionMean rings) run through "
        "compose-api's runner gives, at every 30 s instant of the first hour, each ring's TNF equal to the bolus mass "
        "times the per-unit series the 24 h process-level run recorded (exposure_24h_band1.json), within rel 1e-9. "
        "Generated by checks/spatial/make_field_replay.py.")
    case_dir = HERE / case_name
    case_dir.mkdir(exist_ok=True)
    (case_dir / "document.pbg").write_text(json.dumps(far.document(None), separators=(",", ":")) + "\n")
    case = {"description": description, "scale_level": "abstract", "document": "document.pbg", "interval": END,
            "expect": expect}
    (case_dir / "case.yaml").write_text(yaml.safe_dump(case, sort_keys=False, width=120))
    print(f"wrote {case_name}: {len(expect)} expectations")


if __name__ == "__main__":
    main()
