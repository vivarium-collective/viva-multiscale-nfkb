"""Generate checks/kinetic/stimulus-through-port/: the first join that needs U1 (viva-tellurium 0.2.3, parameters_in).

The driven Lipniacki model (no TNF_stimulation event), seeded through ``species_overrides`` with the pre-equilibrated
state, receives its stimulus through the new ``parameters_in`` port: a store holding ``{"TNF_R": 1.0}`` from t = 0.
That must reproduce what BioModels' original model does after its own event fires at t = 363600 s.

Oracle, another engine: COPASI's sim1 trajectory (viva-biomodels corpus_timecourse.parquet, the same source as
sim1-original) at every post-stimulus corpus point, shifted by 363600 s, for every floating species, rel 1e-3 and
abs 1e-7. sim1's grid is k x 385.2 s and the event time 363600 s is not on it, so the composite steps every 1.2 s, the
largest step that divides both (385.2 = 321 x 1.2, 363600 = 303000 x 1.2). Every compared time is then an exact row.

Negative (run by hand, recorded in the commit): the store set to TNF_R = 0 leaves the cell at rest and fails.

    uv run --project compose --with pyarrow --with pandas python -I checks/kinetic/make_stimulus_through_port.py \
        --corpus ~/viva/viva-biomodels/datasets/corpus_comparison/corpus_timecourse.parquet
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
from pathlib import Path

import pandas as pd
import yaml

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "workspace/datasets/lipniacki2004/processed"
MODEL = DATA / "lipniacki2004_driven.xml"
STATE = DATA / "lipniacki2004_steady_state.json"
CASE = Path(__file__).resolve().parent / "stimulus-through-port"
STIMULUS, STEP = 363600.0, 1.2


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--corpus", type=Path, required=True)
    corpus = parser.parse_args().corpus.expanduser()

    seed = json.loads(STATE.read_text())
    if seed["model_sha256"] != hashlib.sha256(MODEL.read_bytes()).hexdigest():
        raise SystemExit("the saved state was made from another model file; rerun preequilibrate.py")
    species = seed["species"]

    frame = pd.read_parquet(corpus, filters=[("biomodel_id", "==", "BIOMD0000000786")])
    copasi = frame[(frame.engine == "copasi") & (frame.job == "sim1")]
    after = sorted(float(t) - STIMULUS for t in copasi.time.unique() if float(t) > STIMULUS)
    end = after[-1]

    expect: list[dict[str, object]] = [{"kind": "rows", "emitter": "emitter", "min": round(end / STEP) + 1}]
    for t in after:
        row = round(t / STEP)
        if abs(row * STEP - t) > 1e-3:
            raise SystemExit(f"post-stimulus time {t} is not a multiple of {STEP}")
        at = copasi[copasi.time == t + STIMULUS].set_index("variable").value
        for sid in species:
            expect.append({"kind": "scalar", "emitter": "emitter", "field": f"species.{sid}", "row": row,
                           "expected": float(at[sid]), "rel": 1e-3, "abs": 1e-7})

    CASE.mkdir(exist_ok=True)
    shutil.copyfile(MODEL, CASE / MODEL.name)
    document = {
        "state": {
            "stimulus": {"TNF_R": 1.0},
            "kinetic": {
                "_type": "process",
                "address": "local:viva_tellurium.processes.TelluriumProcess",
                "config": {"model_file": MODEL.name, "bulk_species": False, "species_overrides": species},
                "interval": STEP,
                "inputs": {"parameters_in": ["stimulus"]},
                "outputs": {"species": ["species"], "time": ["kinetic_time"]},
            },
            "emitter": {
                "_type": "step",
                "address": "local:RAMEmitter",
                "config": {"emit": {"species": "map[float]", "global_time": "float"}},
                "inputs": {"species": ["species"], "global_time": ["global_time"]},
            },
        },
        "global_time_precision": 6,
    }
    (CASE / "document.pbg").write_text(json.dumps(document, indent=2) + "\n")
    case = {
        "description": (
            "The driven Lipniacki 2004 model (TNF_stimulation removed) in TelluriumProcess (viva-tellurium 0.2.3), seeded "
            "with the pre-equilibrated state and stimulated through the parameters_in port (TNF_R = 1 from t = 0), "
            "reproduces the original model after its event: every floating species at every post-stimulus point of "
            "COPASI's sim1 (viva-biomodels corpus, shifted by 363600 s), rel 1e-3. Steps of 1.2 s put every compared time "
            "on a row. Generated by checks/kinetic/make_stimulus_through_port.py."
        ),
        "scale_level": "molecule",
        "document": "document.pbg",
        "files": [MODEL.name],
        "interval": round(end, 6),
        "expect": expect,
    }
    (CASE / "case.yaml").write_text(yaml.safe_dump(case, sort_keys=False, width=120))
    print(f"wrote {CASE.relative_to(ROOT)}: {len(expect)} expectations at rows {[round(t / STEP) for t in after]}")


if __name__ == "__main__":
    main()
