"""Generate checks/kinetic/preequilibrated-steady/: the driven model in TelluriumProcess, seeded through
``species_overrides`` with the saved pre-equilibrated state (workspace/datasets/lipniacki2004/processed/
lipniacki2004_steady_state.json) and left unstimulated (TNF_R = 0), stays there for 10 h of model time, and that state
is COPASI's own pre-stimulus state.

Two oracles, both independent of TelluriumProcess:
- invariance: after 36000 s every floating species equals the seed, rel 1e-6;
- another engine: the seed equals COPASI's sim1 state at t = 360162 s, the last corpus point before the original
  model's stimulus (viva-biomodels corpus_timecourse.parquet; the original and driven models are identical before
  the event), rel 1e-3, abs 1e-7.

    uv run --project compose --with pyarrow --with pandas python -I checks/kinetic/make_preequilibrated_steady.py \
        --corpus ~/viva/viva-biomodels/datasets/corpus_comparison/corpus_timecourse.parquet
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
from pathlib import Path

import pandas as pd
import yaml

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "workspace/datasets/lipniacki2004/processed"
MODEL = DATA / "lipniacki2004_driven.xml"
STATE = DATA / "lipniacki2004_steady_state.json"
CASE = Path(__file__).resolve().parent / "preequilibrated-steady"
STEP, DURATION, PRE_STIMULUS = 360.0, 36000.0, 360162.0


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--corpus", type=Path, required=True)
    corpus = parser.parse_args().corpus.expanduser()

    seed = json.loads(STATE.read_text())
    if seed["model_sha256"] != hashlib.sha256(MODEL.read_bytes()).hexdigest():
        raise SystemExit("the saved state was made from another model file; rerun preequilibrate.py")
    species = seed["species"]

    frame = pd.read_parquet(corpus, filters=[("biomodel_id", "==", "BIOMD0000000786")])
    copasi = frame[(frame.engine == "copasi") & (frame.job == "sim1") & (frame.time == PRE_STIMULUS)]
    reference = dict(zip(copasi.variable, copasi.value.astype(float), strict=True))

    last = round(DURATION / STEP)
    expect: list[dict[str, object]] = [{"kind": "rows", "emitter": "emitter", "min": last + 1}]
    for sid, value in species.items():
        expect.append({"kind": "scalar", "emitter": "emitter", "field": f"species.{sid}", "row": last,
                       "expected": value, "rel": 1e-6, "abs": 1e-12})
        expect.append({"kind": "scalar", "emitter": "emitter", "field": f"species.{sid}", "row": last,
                       "expected": reference[sid], "rel": 1e-3, "abs": 1e-7})

    CASE.mkdir(exist_ok=True)
    shutil.copyfile(MODEL, CASE / MODEL.name)
    document = {
        "state": {
            "kinetic": {
                "_type": "process",
                "address": "local:viva_tellurium.processes.TelluriumProcess",
                "config": {"model_file": MODEL.name, "bulk_species": False, "species_overrides": species},
                "interval": STEP,
                "inputs": {},
                "outputs": {"species": ["species"], "time": ["kinetic_time"]},
            },
            "emitter": {
                "_type": "step",
                "address": "local:RAMEmitter",
                "config": {"emit": {"species": "map[float]", "global_time": "float"}},
                "inputs": {"species": ["species"], "global_time": ["global_time"]},
            },
        },
        "global_time_precision": 6,
    }
    (CASE / "document.pbg").write_text(json.dumps(document, indent=2) + "\n")
    case = {
        "description": (
            "The driven Lipniacki 2004 model (TNF_stimulation removed) in TelluriumProcess, seeded through "
            "species_overrides with the saved pre-equilibrated state and left unstimulated, holds that state for "
            f"{DURATION:.0f} s (every species, rel 1e-6), and the state equals COPASI's sim1 state at t = "
            f"{PRE_STIMULUS:.0f} s, before the original model's stimulus (viva-biomodels corpus, rel 1e-3). "
            "Generated by checks/kinetic/make_preequilibrated_steady.py."
        ),
        "scale_level": "molecule",
        "document": "document.pbg",
        "files": [MODEL.name],
        "interval": DURATION,
        "expect": expect,
    }
    (CASE / "case.yaml").write_text(yaml.safe_dump(case, sort_keys=False, width=120))
    print(f"wrote {CASE.relative_to(ROOT)}: {len(expect)} expectations")


if __name__ == "__main__":
    main()
