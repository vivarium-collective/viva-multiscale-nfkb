"""The race on Calzone's network: fate fractions at t = 40 Calzone units across transcription rates, TNF on.

Writes documentation/design/_transrate_table.md, which design/time.md includes; science/boolean-networks.md quotes its
first and last rows. The coupled network with u_NFkB = 1, d_NFkB = 0, k_time = 1 and absorb_death = 0 is Calzone's
network exactly (checks/boolean/coupled-equals-full), so r_tx plays TransRate here. Each row is a fraction of 50,000
cells (MaBoSS trajectories, one seed per run), over MaBoSS's last window [39, 40].

    uv run --project compose python -I documentation/science/code/transrate_race.py           # write the table
    uv run --project compose python -I documentation/science/code/transrate_race.py --check   # fail if it is stale
"""

import argparse
import sys
from fractions import Fraction
from pathlib import Path

from process_bigraph import allocate_core
from viva_maboss.processes import MaBoSSProcess

ROOT = Path(__file__).resolve().parents[3]
NETWORK = (ROOT / "workspace" / "datasets" / "calzone2010_cellfate" / "processed" / "cellfate_coupled.bnd").read_text()
OUT = ROOT / "documentation" / "design" / "_transrate_table.md"
AS_CALZONE = {"High_NFkB": 0.0, "Low_CASP8": 0.0, "Low_RIP1": 0.0, "Low_cIAP": 0.0, "u_TNF": 0.0, "d_TNF": 0.0,
              "u_NFkB": 1.0, "d_NFkB": 0.0, "k_time": 1.0, "absorb_death": 0.0}
RATES = (Fraction(1, 24), Fraction(1, 8), Fraction(1, 4), Fraction(1, 2), Fraction(1))
UNITS, CELLS, WINDOWS, SEED = 40.0, 50_000, 40, 3


def fates(transrate: float) -> dict[str, float]:
    process = MaBoSSProcess(
        config={"network": NETWORK, "parameters": {**AS_CALZONE, "r_tx": transrate},
                "initial_state": {"FADD": 1, "ATP": 1, "cIAP": 1, "TNF": 1}, "sample_count": CELLS,
                "windows_per_interval": WINDOWS, "seed": SEED},
        core=allocate_core())
    start = process.initial_state()
    deltas = process.update(start, UNITS)["node_probabilities"]
    return {n: start["node_probabilities"][n] + deltas[n] for n in ("Survival", "Apoptosis", "NonACD")}


def table() -> str:
    rows = ["<!-- Generated by documentation/science/code/transrate_race.py; do not edit. -->",
            "| TransRate | Survival | Apoptosis | NonACD |", "|---|---|---|---|"]
    for rate in RATES:
        p = fates(float(rate))
        label = f"{rate}" + (" (MaBoSS's example)" if rate == Fraction(1, 24) else "")
        rows.append(f"| {label} | {p['Survival']:.3f} | {p['Apoptosis']:.3f} | {p['NonACD']:.3f} |")
    return "\n".join(rows) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if the committed table differs")
    args = parser.parse_args()
    text = table()
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit(f"transrate_race.py: {OUT.relative_to(ROOT)} is stale; rerun without --check")
        print(f"{OUT.relative_to(ROOT)} is current")
        return
    OUT.write_text(text)
    print(text, end="")


if __name__ == "__main__":
    main()
